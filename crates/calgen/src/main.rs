//! Generates `crates/time-core/src/hijri_table.rs` from ICU4X's Umm al-Qura data.
//! Run: `cargo run -q -p calgen > crates/time-core/src/hijri_table.rs`
//! and `cargo run -q -p calgen -- world > crates/time-core/src/world_cal_table.rs`
//! The output is committed, so the site and Wasm never depend on ICU.

use icu_calendar::Date;
use icu_calendar::cal::Hijri;

const FIRST_YEAR: i32 = 1300;
const LAST_YEAR: i32 = 1600;

/// Rata die of 1970-01-01.
const UNIX_RD: i64 = 719_163;

type Uq = Date<Hijri<icu_calendar::cal::hijri::UmmAlQura>>;

fn month_start(year: i32, month: u8) -> Option<i64> {
    let d: Uq = Date::try_new_hijri_with_calendar(year, month, 1, Hijri::new_umm_al_qura()).ok()?;
    Some(d.to_rata_die().to_i64_date() - UNIX_RD)
}

fn main() {
    if std::env::args().nth(1).as_deref() == Some("world") {
        world::print();
        return;
    }
    let iso = Date::try_new_iso(1970, 1, 1).expect("valid date");
    assert_eq!(
        iso.to_rata_die().to_i64_date(),
        UNIX_RD,
        "rata die epoch changed"
    );

    // Umm al-Qura is an official calculation only for these years (1882-2174 CE); ICU extends it
    // with an approximation outside them, which we deliberately do not publish.
    let (first, last) = (FIRST_YEAR, LAST_YEAR);

    let mut rows = Vec::new();
    let mut prev_end: Option<i64> = None;
    for y in first..=last {
        let starts: Vec<i64> = (1..=12)
            .map(|m| month_start(y, m).expect("checked"))
            .collect();
        let next = month_start(y + 1, 1).expect("checked");
        if let Some(p) = prev_end {
            assert_eq!(p, starts[0], "gap between years {} and {y}", y - 1);
        }
        let mut mask = 0u16;
        for m in 0..12 {
            let end = if m == 11 { next } else { starts[m + 1] };
            match end - starts[m] {
                30 => mask |= 1 << m,
                29 => {}
                n => panic!("month {} of {y} has {n} days", m + 1),
            }
        }
        prev_end = Some(next);
        rows.push((starts[0], mask));
    }

    println!(
        "// @generated by `cargo run -p calgen` from icu_calendar (Umm al-Qura). Do not edit by hand."
    );
    println!(
        "// Per Hijri year: days since 1970-01-01 of 1 Muharram, and a mask where bit (month - 1) set means 30 days."
    );
    println!("pub const FIRST_YEAR: i32 = {first};");
    println!("pub const LAST_YEAR: i32 = {last};");
    println!("pub const YEARS: [(i32, u16); {}] = [", rows.len());
    for (start, mask) in &rows {
        println!("    ({start}, 0x{mask:03X}),");
    }
    println!("];");
}

/// Hebrew, Chinese, Persian and Indian national month tables, found by walking every day.
mod world {
    use icu_calendar::cal::{ChineseTraditional, Hebrew, Indian, Persian};
    use icu_calendar::types::RataDie;
    use icu_calendar::{AsCalendar, Calendar, Date};

    /// One calendar year: start (days since 1970-01-01), month lengths, leap-month ordinal (0 = none).
    struct Year {
        year: i32,
        start: i64,
        lens: Vec<u8>,
        leap: u8,
    }

    fn walk<C: Calendar + Copy, A: AsCalendar<Calendar = C> + Copy>(
        cal: A,
        first: i32,
        last: i32,
        year_of: impl Fn(&Date<A>) -> i32,
    ) -> Vec<Year> {
        // Start well before the first year; scan forward day by day.
        let mut rd = super::UNIX_RD - 200 * 366 - 400 * 366;
        let mut out: Vec<Year> = Vec::new();
        let mut cur: Option<Year> = None;
        loop {
            let d = Date::from_rata_die(RataDie::new(rd), cal);
            let y = year_of(&d);
            if y > last + 1 {
                break;
            }
            if d.day_of_month().0 == 1 {
                let m = d.month();
                if m.ordinal == 1 {
                    if let Some(done) = cur.take()
                        && (first..=last).contains(&done.year)
                    {
                        out.push(done);
                    }
                    cur = Some(Year {
                        year: y,
                        start: rd - super::UNIX_RD,
                        lens: Vec::new(),
                        leap: 0,
                    });
                }
                if let Some(c) = cur.as_mut() {
                    c.lens.push(d.days_in_month());
                    if m.to_input().is_leap() {
                        c.leap = m.ordinal;
                    }
                }
            }
            rd += 1;
        }
        assert_eq!(out.len() as i32, last - first + 1, "missing years");
        for w in out.windows(2) {
            assert_eq!(w[0].year + 1, w[1].year);
            let total: i64 = w[0].lens.iter().map(|&l| i64::from(l)).sum();
            assert_eq!(w[0].start + total, w[1].start, "gap after {}", w[0].year);
        }
        out
    }

    fn emit(name: &str, rows: &[Year]) {
        println!("pub const {name}_FIRST: i32 = {};", rows[0].year);
        println!("pub const {name}: [(i32, u32, u8); {}] = [", rows.len());
        for r in rows {
            let mut code = 0u32;
            for (i, &l) in r.lens.iter().enumerate() {
                assert!(
                    (29..=31).contains(&l),
                    "{name} {} month {} has {l} days",
                    r.year,
                    i + 1
                );
                code |= u32::from(l - 29) << (2 * i);
            }
            // Month count is implied by the leap marker (12 + 1 if leap) for lunisolar calendars.
            assert_eq!(
                r.lens.len(),
                12 + usize::from(r.leap > 0),
                "{name} {}",
                r.year
            );
            println!("    ({}, 0x{code:07X}, {}),", r.start, r.leap);
        }
        println!("];");
    }

    pub fn print() {
        println!(
            "// @generated by `cargo run -p calgen -- world` from icu_calendar. Do not edit by hand."
        );
        println!(
            "// Per year: days since 1970-01-01 of the first day, month lengths as 2 bits each"
        );
        println!(
            "// (length - 29, month 1 in the low bits), and the ordinal of the leap month (0 = none)."
        );
        let hebrew = walk(Hebrew, 5600, 6000, |d| d.year().extended_year());
        emit("HEBREW", &hebrew);
        let chinese = walk(ChineseTraditional::new(), 1900, 2100, |d| {
            d.cyclic_year().related_iso
        });
        emit("CHINESE", &chinese);
        let persian = walk(Persian, 1200, 1500, |d| d.year().extended_year());
        emit("PERSIAN", &persian);
        let indian = walk(Indian, 1800, 2100, |d| d.year().extended_year());
        emit("INDIAN", &indian);
    }
}
