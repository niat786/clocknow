//! Generates `crates/time-core/src/hijri_table.rs` from ICU4X's Umm al-Qura data.
//! Run: `cargo run -q -p calgen > crates/time-core/src/hijri_table.rs`
//! The output is committed, so the site and Wasm never depend on ICU.

use icu_calendar::Date;
use icu_calendar::cal::Hijri;

const FIRST_YEAR: i32 = 1300;
const LAST_YEAR: i32 = 1600;

/// Rata die of 1970-01-01.
const UNIX_RD: i64 = 719_163;

type Uq = Date<Hijri<icu_calendar::cal::hijri::UmmAlQura>>;

fn month_start(year: i32, month: u8) -> Option<i64> {
    let d: Uq = Date::try_new_hijri_with_calendar(year, month, 1, Hijri::new_umm_al_qura()).ok()?;
    Some(d.to_rata_die().to_i64_date() - UNIX_RD)
}

fn main() {
    let iso = Date::try_new_iso(1970, 1, 1).expect("valid date");
    assert_eq!(
        iso.to_rata_die().to_i64_date(),
        UNIX_RD,
        "rata die epoch changed"
    );

    // Umm al-Qura is an official calculation only for these years (1882-2174 CE); ICU extends it
    // with an approximation outside them, which we deliberately do not publish.
    let (first, last) = (FIRST_YEAR, LAST_YEAR);

    let mut rows = Vec::new();
    let mut prev_end: Option<i64> = None;
    for y in first..=last {
        let starts: Vec<i64> = (1..=12)
            .map(|m| month_start(y, m).expect("checked"))
            .collect();
        let next = month_start(y + 1, 1).expect("checked");
        if let Some(p) = prev_end {
            assert_eq!(p, starts[0], "gap between years {} and {y}", y - 1);
        }
        let mut mask = 0u16;
        for m in 0..12 {
            let end = if m == 11 { next } else { starts[m + 1] };
            match end - starts[m] {
                30 => mask |= 1 << m,
                29 => {}
                n => panic!("month {} of {y} has {n} days", m + 1),
            }
        }
        prev_end = Some(next);
        rows.push((starts[0], mask));
    }

    println!(
        "// @generated by `cargo run -p calgen` from icu_calendar (Umm al-Qura). Do not edit by hand."
    );
    println!(
        "// Per Hijri year: days since 1970-01-01 of 1 Muharram, and a mask where bit (month - 1) set means 30 days."
    );
    println!("pub const FIRST_YEAR: i32 = {first};");
    println!("pub const LAST_YEAR: i32 = {last};");
    println!("pub const YEARS: [(i32, u16); {}] = [", rows.len());
    for (start, mask) in &rows {
        println!("    ({start}, 0x{mask:03X}),");
    }
    println!("];");
}
